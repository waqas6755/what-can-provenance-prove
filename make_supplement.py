L.append(r"\section{S3. G3 per run (DistilBERT, SST-2)}" "\n" r"\small\begin{longtable}{rrrrrrrr}\toprule $n$ & seed & ASR \% & 95\% CI & adj.\ pts & recall \% (TP/$n$) & 95\% CI & FP (FPR \%)\\\midrule")
