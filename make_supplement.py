L.append(r"\section{S1. Prototype versus model (E2), per profile}" "\n" r"\begin{tabular}{lrrrrrr}\toprule Profile & instances & executions & accepted & unsound & realised & not realised\\\midrule")
for k, v in st["E2_recount"]["per_profile"].items():
    L.append(f"{esc(k)} & {v['instances']:,} & {v['executions']:,} & {v['accepted']:,} & {v['unsound']} & {v['realised']:,} & {v['not_realised']}\\\\")
L.append(rf"\midrule Total & & {st['E2_recount']['total_executions']:,} & {st['E2_recount']['total_accepted']:,} & & & \\\bottomrule\end{{tabular}}")
L.append(r"""\par\smallskip Executions are counted once per (profile, pipeline type, mechanism set); the adversary stops early for a mechanism set once every goal has been violated, which is why weak mechanism sets contribute fewer executions.""")
# S2 lattice
L.append(r"\section{S2. Full adversary lattice}")
L.append(rf"""A vectorised checker (\texttt{{model/adversary\_lattice.py}}) was validated against all {esc(lat['validated_against_alloy'])} Alloy results and then decided {lat['decisions']:,} instances (all $2^7$ adversary subsets $\times$ 128 mechanism sets $\times$ 2 pipeline types $\times$ 6 goals).
Monotone in mechanisms: {lat['monotone_in_mechanisms']}. Anti-monotone in adversary capabilities: {lat['antimonotone_in_adversary']}. Number of (adversary, pipeline, goal) cases with no achieving mechanism set: {lat['n_unreachable_cases']} of {128*2*6}.
\par\medskip\begin{{tabular}}{{lrr}}\toprule Theorem statement checked & instances in scope & mismatches\\\midrule""")
for k, v in thm.items():
    L.append(f"{esc(k)} & {v['instances_in_scope']:,} & {v['mismatches']}\\\\")
L.append(r"\bottomrule\end{tabular}")
